"""Python code: codeparrot-clean-valid, permissively licensed files only.

Why not ``bigcode/the-stack-smol``: it is gated, and more to the point its
Python subset is 10k files (~87 MB with metadata, roughly 20M tokens) --
nowhere near the ~90M-token code slice, gated or not.
``codeparrot/codeparrot-clean-valid`` is ungated, already deduplicated and
filtered for autogenerated files and extreme line lengths, and holds ~600M
characters of Python in 61,373 files.

The original plan chose the-stack-smol partly because it is permissive-only.
codeparrot is not -- it includes GPL and AGPL files -- so this loader keeps
only permissive licenses.  That keeps ~63% of the files: roughly 110M tokens
at the dev tokenizer's 3.4 chars/token, so the 90M target is met with ~20%
headroom, not more.  If a later mixture needs more code, ``codeparrot-clean``
(the training split of the same corpus, deduplicated against this one) is the
natural extension.
"""

from __future__ import annotations

from collections import Counter
from typing import Iterable, Iterator

from ..document import Document, make_id
from .hf import HFSource, field, stream_rows

SOURCE = HFSource(
    dataset="codeparrot/codeparrot-clean-valid",
    config=None,
    splits=("train",),
    revision="4db92d2ec0c1b4c41eeb439cfae16854511d9dcd",
    license="per-file (permissive subset kept)",
)

PERMISSIVE = frozenset({
    "mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "unlicense", "cc0-1.0",
})


def row_to_document(row: dict, stats: Counter | None = None) -> Document | None:
    stats = stats if stats is not None else Counter()
    license_ = str(field(row, "license", SOURCE)).lower()
    if license_ not in PERMISSIVE:
        stats[f"skipped_license:{license_}"] += 1
        return None
    if row.get("autogenerated"):
        stats["skipped_autogenerated"] += 1
        return None
    text = field(row, "content", SOURCE)
    if not text or not text.strip():
        stats["skipped_empty"] += 1
        return None
    stats["kept"] += 1
    return Document(
        id=make_id("codeparrot", field(row, "repo_name", SOURCE), field(row, "path", SOURCE)),
        source="general",
        text=text,
        author="codeparrot",
        meta={"slice": "code", "license": license_},
    )


def iter_documents(rows: Iterable[dict] | None = None, stats: Counter | None = None) -> Iterator[Document]:
    stats = stats if stats is not None else Counter()
    for row in stream_rows(SOURCE) if rows is None else rows:
        doc = row_to_document(row, stats)
        if doc is not None:
            yield doc
