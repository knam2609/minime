def test_tokenizer_sample_is_deterministic_train_only_and_budgeted():
    docs = docs_for(3000)
    a = [d.id for d in sample_documents(docs, 20_000, seed=0)]
    b = [d.id for d in sample_documents(docs, 20_000, seed=0)]
    c = [d.id for d in sample_documents(docs, 20_000, seed=1)]
    assert a == b and a != c
    assert all(assign_split(i_doc.id, GENERAL_RATIOS) == "train"
               for i_doc in docs if i_doc.id in set(a))
    chars = sum(len(d.text) for d in docs if d.id in set(a))
    assert 20_000 <= chars < 20_000 + max(len(d.text) for d in docs)


