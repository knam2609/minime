def docs_for(n: int, start: int = 0) -> list[Document]:
    return list(fineweb.iter_documents(web_rows(n, start)))


def test_ingest_stops_at_the_target_and_records_the_tokenizer(tmp_path, small_tok):
    summary = ingest_slice(docs_for(2000), small_tok, tmp_path, "web", 5_000,
                           source={"dataset": "fake"}, batch_docs=16, log=lambda _: None)
    train = TokenShard(tmp_path / "web.train")
    assert not summary["exhausted"]
    assert 5_000 <= train.n_tokens < 5_000 + 16 * 200  # never cuts a document; overshoot < 1 batch
    for split in ("train", "val", "test"):
        meta = json.loads((tmp_path / f"web.{split}.meta.json").read_text())
        assert meta["tokenizer"] == small_tok.id  # fingerprint travels with the shard
        assert meta["tokenizer"].endswith(small_tok.fingerprint())
        assert meta["extra"]["split"] == split
    assert summary["splits"]["train"]["tokens"] == train.n_tokens


def test_overshoot_is_about_one_document_not_one_batch(tmp_path, small_tok):
    # Big batches and a small target: the regime that overshot a 1M smoke
    # target by 61% before batches shrank near the target.
    docs = docs_for(2000)
    longest = max(len(small_tok.encode(d.text)) + 1 for d in docs)
    ingest_slice(docs, small_tok, tmp_path, "web", 3_000, batch_docs=512, log=lambda _: None)
    overshoot = TokenShard(tmp_path / "web.train").n_tokens - 3_000
    assert 0 <= overshoot <= longest


def test_ingest_splits_by_document_hash_and_roundtrips(tmp_path, small_tok):
    docs = docs_for(400)
    ratios = {"train": 0.6, "val": 0.2, "test": 0.2}
    ingest_slice(docs, small_tok, tmp_path, "web", 10**9, ratios=ratios, batch_docs=32,
                 log=lambda _: None)
    expected = Counter(assign_split(d.id, ratios) for d in docs)
    decoded: dict[str, list[str]] = {}
    for split in ("train", "val", "test"):
        shard = TokenShard(tmp_path / f"web.{split}")
        assert shard.n_docs == expected[split]
        decoded[split] = [small_tok.decode(d) for d in shard.documents()]
        assert all(int(d[-1]) == small_tok.eot_id for d in shard.documents())
    by_split = {s: [d.text for d in docs if assign_split(d.id, ratios) == s] for s in expected}
    assert decoded == by_split  # exact text, stream order, right split


def test_ingest_leaves_no_raw_text_behind(tmp_path, small_tok):
    ingest_slice(docs_for(100), small_tok, tmp_path, "web", 10**9, log=lambda _: None)
    names = sorted(p.name for p in tmp_path.iterdir())
    assert all(n.endswith((".bin", ".idx.npy", ".meta.json")) for n in names), names
    assert not (tmp_path / "_incomplete").exists()


def test_exhausted_stream_is_recorded_not_hidden(tmp_path, small_tok):
    messages = []
    summary = ingest_slice(docs_for(20), small_tok, tmp_path, "web", 10**9, log=messages.append)
    assert summary["exhausted"]
    assert any("WARNING" in m and "short" in m for m in messages)
    meta = json.loads((tmp_path / "web.train.meta.json").read_text())
    assert meta["extra"]["summary"]["exhausted"] is True


def test_ingestion_is_byte_identical_across_runs(tmp_path, small_tok):
    for run in ("a", "b"):
        ingest_slice(docs_for(300), small_tok, tmp_path / run, "web", 4_000, batch_docs=8,
                     log=lambda _: None)
    for split in ("train", "val", "test"):
        a = (tmp_path / "a" / f"web.{split}.bin").read_bytes()
        b = (tmp_path / "b" / f"web.{split}.bin").read_bytes()
        assert a == b, split


def test_a_crash_leaves_nothing_that_looks_like_data(tmp_path, small_tok):
    def dies_midway():
        yield from docs_for(50)
        raise ConnectionError("stream dropped")

    with pytest.raises(ConnectionError):
        ingest_slice(dies_midway(), small_tok, tmp_path, "web", 10**9, batch_docs=8, log=lambda _: None)
    assert not list(tmp_path.glob("*.bin"))
    # and the next run clears the stale staging directory
    ingest_slice(docs_for(50), small_tok, tmp_path, "web", 10**9, log=lambda _: None)
    assert (tmp_path / "web.train.bin").exists() and not (tmp_path / "_incomplete").exists()


def test_completed_slice_is_recognised_only_with_identical_settings(tmp_path, small_tok):
    source = {"dataset": "fake", "revision": "abc"}
    ingest_slice(docs_for(100), small_tok, tmp_path, "web", 2_000, source=source, log=lambda _: None)
    same = slice_settings(source, small_tok.id, 2_000)
    assert completed_slice(tmp_path, "web", same) is not None
    assert completed_slice(tmp_path, "web", slice_settings(source, small_tok.id, 3_000)) is None
    assert completed_slice(tmp_path, "web", slice_settings({**source, "revision": "def"}, small_tok.id, 2_000)) is None
    assert completed_slice(tmp_path, "web", slice_settings(source, "other@123", 2_000)) is None
    assert completed_slice(tmp_path, "code", same) is None


def test_combine_concatenates_documents_and_refuses_mixed_tokenizers(tmp_path, small_tok):
    ratios = {"train": 0.5, "val": 0.25, "test": 0.25}
    ingest_slice(docs_for(80), small_tok, tmp_path, "web", 10**9, ratios=ratios, log=lambda _: None)
    ingest_slice(docs_for(80, start=80), small_tok, tmp_path, "code", 10**9, ratios=ratios, log=lambda _: None)
    meta = combine_shards([tmp_path / "web.val", tmp_path / "code.val"], tmp_path / "val", small_tok.id)
    parts = [TokenShard(tmp_path / "web.val"), TokenShard(tmp_path / "code.val")]
    combined = TokenShard(tmp_path / "val")
    assert meta.n_tokens == sum(p.n_tokens for p in parts)
    assert combined.n_docs == sum(p.n_docs for p in parts)
    assert np.array_equal(np.asarray(combined.tokens), np.concatenate([np.asarray(p.tokens) for p in parts]))

    other = json.loads((tmp_path / "code.val.meta.json").read_text())
    other["tokenizer"] = "someone-else@0000"
    (tmp_path / "code.val.meta.json").write_text(json.dumps(other))
    with pytest.raises(ValueError, match="different tokenizers"):
        combine_shards([tmp_path / "web.val", tmp_path / "code.val"], tmp_path / "val2", small_tok.id)


def test_mixture_of_shards_from_two_tokenizers_is_refused(tmp_path, small_tok):
    ingest_slice(docs_for(50), small_tok, tmp_path, "web", 10**9, log=lambda _: None)
    shards = {"web": TokenShard(tmp_path / "web.train")}
    assert common_tokenizer(shards) == small_tok.id
    other = json.loads((tmp_path / "web.val.meta.json").read_text())
    other["tokenizer"] = "char@abc"
    (tmp_path / "web.val.meta.json").write_text(json.dumps(other))
    shards["val"] = TokenShard(tmp_path / "web.val")
    with pytest.raises(ValueError, match="different tokenizers"):
        common_tokenizer(shards)


def test_free_space_guard(tmp_path):
    check_free_space(tmp_path / "not" / "yet" / "made", 1)
    with pytest.raises(RuntimeError, match="MINIME_DATA_ROOT"):
        check_free_space(tmp_path, 2**62)
    full = estimate_bytes({s.name: s.target_tokens for s in GENERAL_SLICES.values()})
    assert 1.8 * 2**30 < full < 2.5 * 2**30  # ~900M uint16 tokens plus held-out copies


