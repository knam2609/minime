def _run_script(module_name: str, argv: list[str]) -> int:
    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    try:
        module = __import__(module_name)
        return module.main(argv)
    finally:
        sys.path.remove(str(REPO_ROOT / "scripts"))


@pytest.mark.slow
def test_prepare_then_train_with_bpe_end_to_end(tmp_path, small_tok):
    tok_path = tmp_path / "fixture-dev.json"
    small_tok.save(tok_path)
    out = tmp_path / "shards"
    assert _run_script("prepare_data", [
        "--docs", str(FIXTURE / "sam.jsonl"), "--out", str(out), "--by-source",
        "--tokenizer", "bpe", "--tokenizer-path", str(tok_path),
    ]) == 0

    manifest = json.loads((out / "manifest.json").read_text())
    assert manifest["tokenizer_fingerprint"] == small_tok.fingerprint()
    assert manifest["tokenizer_dev"] is True
    assert manifest["vocab_size"] == 400

    names = ["chat", "longform", "code"]
    shards = {n: TokenShard(out / f"{n}.train") for n in names}
    val = TokenShard(out / "val")
    assert common_tokenizer({**shards, "val": val}) == small_tok.id
    first = next(shards["chat"].documents())
    assert int(first[-1]) == small_tok.eot_id and EOT not in small_tok.decode(first)

    model_cfg = ModelConfig(vocab_size=manifest["vocab_size"], d_model=32, n_heads=4,
                            n_layers=2, context_length=32)
    training = TrainingConfig(batch_size=4, max_steps=6, warmup_steps=2, validation_interval=3,
                              validation_batches=1, log_interval=3, checkpoint_interval=6,
                              device="cpu", precision="fp32")
    cfg = Config(name="bpe-e2e", model=model_cfg, training=training,
                 data=DataConfig(mixture={n: 1.0 for n in names}))
    trainer = Trainer(
        config=cfg, model=build_model(model_cfg),
        sampler=MixtureSampler(shards, {n: 1.0 for n in names}, context_length=32, batch_size=4),
        val_batches=make_val_batches(val, context_length=32, batch_size=4, n_batches=1),
        run_dir=tmp_path / "run", costs_path=tmp_path / "costs.csv",
        data_info={"tokenizer": small_tok.id},
    )
    summary = trainer.train()
    assert np.isfinite(summary["final_val_loss"])
    run_manifest = json.loads((tmp_path / "run" / "manifest.json").read_text())
    assert run_manifest["data"]["tokenizer"] == small_tok.id


