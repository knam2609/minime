def _flaky_opener(rows: list[dict], fail_at: list[int]):
    """Opens a split whose stream dies once at each position in ``fail_at``."""
    pending = list(fail_at)

    def open_split(split):
        def gen():
            for i, row in enumerate(rows):
                if pending and i == pending[0]:
                    pending.pop(0)
                    raise ConnectionError("Server Disconnected")
                yield row
        return gen()

    return open_split


def test_stream_survives_dropped_connections_without_duplicating_rows():
    from minime.data.sources.hf import HFSource, stream_rows

    rows = [{"i": i} for i in range(50)]
    source = HFSource("fake/ds", None, ("train", "test"), "0" * 40, "none")
    messages = []
    got = list(stream_rows(source, _flaky_opener(rows, [0, 7, 30]), wait=0, log=messages.append))
    # both splits, every row exactly once, in order
    assert got == rows + rows
    assert len(messages) == 3 and "after 7 rows" in messages[1]


def test_stream_gives_up_after_repeated_failures_without_progress():
    from minime.data.sources.hf import HFSource, stream_rows

    source = HFSource("fake/ds", None, ("train",), "0" * 40, "none")
    rows = [{"i": i} for i in range(10)]
    with pytest.raises(ConnectionError):
        list(stream_rows(source, _flaky_opener(rows, [3] * 4), attempts=3, wait=0, log=lambda _: None))


def test_stream_does_not_retry_non_network_errors():
    from minime.data.sources.hf import HFSource, stream_rows

    source = HFSource("fake/ds", None, ("train",), "0" * 40, "none")
    calls = []

    def gated(split):
        calls.append(split)
        raise PermissionError("gated")

    with pytest.raises(PermissionError):
        list(stream_rows(source, gated, wait=0, log=lambda _: None))
    assert calls == ["train"]
