def web_rows(n: int, start: int = 0) -> list[dict]:
    return [
        {"id": f"<urn:uuid:{i}>", "text": f"Document {i}. " + "The mitochondria is the powerhouse. " * (i % 7 + 1),
         "url": "http://example.org", "score": 3.1}
        for i in range(start, start + n)
    ]


def chatml(*turns: str, end: str = "\n\n<|end_of_text|>") -> str:
    roles = ("user", "assistant")
    return "".join(f"<|im_start|>{roles[i % 2]}\n{t}<|im_end|>\n" for i, t in enumerate(turns)) + end


def discord_rows() -> list[dict]:
    extra = {"tokens": 30, "turns": 3, "characters": 170, "words": 19}
    return [
        {"text": chatml("hi how are you", "  good thanks, u?  ", "not bad\nhad a long day tho"), **extra},
        {"text": chatml("just one line"), **extra},
        {"text": chatml("", "   "), **extra},
        {"text": chatml("a <|im_start|>user\nnested", "reply"), **extra},
    ]


def code_rows() -> list[dict]:
    base = {"repo_name": "someone/repo", "autogenerated": False}
    return [
        {**base, "path": "a.py", "license": "mit", "content": "def f(x):\n    return x + 1\n"},
        {**base, "path": "b.py", "license": "gpl-3.0", "content": "import os\n"},
        {**base, "path": "c.py", "license": "Apache-2.0", "content": "class A:\n    pass\n"},
        {**base, "path": "d.py", "license": "mit", "content": "x = 1\n", "autogenerated": True},
        {**base, "path": "e.py", "license": "bsd-3-clause", "content": "   \n"},
    ]


